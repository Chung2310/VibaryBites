import { chromium, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
const base = process.env.SMOKE_BASE_URL || 'http://localhost:3102';
const browser = await chromium.launch({ headless: true });
const checks = [];
try {
 const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
 const page = await context.newPage();
 const errors = [];
 page.on('pageerror', error => errors.push(error.message));
 const scripts = [];
 page.on('request', request => { if (request.resourceType() === 'script') scripts.push(request.url()); });
 const response = await page.goto(base + '/about');
 expect(await response.text()).toContain('<h1');
 await expect(page.locator('header').first()).toBeVisible();
 const manifest = JSON.parse(readFileSync('.next-production/react-loadable-manifest.json', 'utf8'));
 const entry = Object.entries(manifest).find(([key]) => key.includes('-> ./mobile-navigation'));
 expect(entry).toBeTruthy();
 const drawerChunk = entry[1].files.at(-1);
 expect(scripts.some(url => url.includes(drawerChunk))).toBe(false);
 await page.locator('header button').click();
 await expect(page.getByRole('dialog')).toBeVisible();
 expect(scripts.some(url => url.includes(drawerChunk))).toBe(true);
 await page.getByRole('dialog').locator('a[href="/about"]').click();
 await expect(page.getByRole('dialog')).toBeHidden();
 checks.push('mobile drawer loads on demand and closes after navigation');
 for (const path of ['/faq', '/how-to-buy', '/contact']) {
  await page.goto(base + path);
  await expect(page.locator('h1').first()).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
 }
 await page.locator('input[name="name"]').fill('Test visitor');
 await page.locator('input[name="email"]').fill('test@example.com');
 await expect(page.locator('input[name="name"]')).toHaveValue('Test visitor');
 checks.push('static pages and contact form render on mobile');
 await page.goto(base + '/quiz');
 await page.locator('input[name="preferredFruits"]').fill('strawberry');
 await page.locator('button').filter({ hasText: /Ti.p theo/ }).click();
 await expect(page.getByRole('radiogroup')).toBeVisible();
 checks.push('lazy quiz advances to next step');
 const catalog = await (await context.request.get(base + '/api/data/cakes?limit=1')).json();
 const product = catalog.data[0];
 expect(product).toBeTruthy();
 await context.addInitScript(product => localStorage.setItem('vibary-cart', JSON.stringify([{ ...product, quantity: 1 }])), product);
 await page.goto(base + '/cart');
 await expect(page.getByText(product.name, { exact: true }).first()).toBeVisible();
 await page.goto(base + '/checkout');
 await page.locator('input[name="name"]').fill('Test buyer');
 await expect(page.locator('input[name="name"]')).toHaveValue('Test buyer');
 checks.push('cart persists and lazy checkout accepts input');
 await page.route('**/api/auth/session', route => route.fulfill({ json: { user: { id: 'preview', username: 'admin' } } }));
 await page.goto(base + '/admin/products/new');
 await expect(page.locator('input[name="name"]')).toBeVisible();
 await page.goto(base + '/admin/news/new');
 await expect(page.locator('input[name="title"]')).toBeVisible();
 await expect(page.locator('[contenteditable="true"]')).toBeVisible();
 checks.push('lazy product and news forms plus rich text editor render');
 expect(errors).toEqual([]);
 console.log(JSON.stringify({ checks, browserErrors: errors }, null, 2));
} finally { await browser.close(); }
